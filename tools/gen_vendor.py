#!/usr/bin/env python3
"""Generate Margin/VendorData.lua: buy prices of vendor-sold tradeskill reagents.

Names are curated below (only items vendors stock without limit); IDs and prices
come from Blizzard's Classic Era ItemSparse table (BuyPrice), e.g. from
https://wago.tools/db2/ItemSparse/csv?build=1.15.9.70576

Usage: gen_vendor.py ItemSparse.csv > Margin/VendorData.lua
"""
import csv, sys

BUILD = "1.15.9.70576"
NAMES = [
    "Coarse Thread", "Fine Thread", "Silken Thread", "Heavy Silken Thread", "Rune Thread",
    "Salt", "Bleach",
    "Empty Vial", "Leaded Vial", "Crystal Vial", "Imbued Vial",
    "Red Dye", "Green Dye", "Blue Dye", "Yellow Dye", "Purple Dye", "Gray Dye", "Black Dye",
    "Mild Spices", "Hot Spices", "Soothing Spices",
    "Weak Flux", "Coal", "Flash Powder", "Simple Wood", "Flint and Tinder",
    "Wooden Stock", "Heavy Stock",
]

found = {}
for r in csv.DictReader(open(sys.argv[1], newline="", encoding="utf-8")):
    n = r["Display_lang"]
    price = int(r["BuyPrice"] or 0)
    if n in NAMES and price > 0:
        if n in found:
            sys.exit("ambiguous name: " + n)
        found[n] = (int(r["ID"]), price)
missing = [n for n in NAMES if n not in found]
if missing:
    sys.exit("not found: " + ", ".join(missing))

print("-- Generated by tools/gen_vendor.py. Do not edit.")
print("-- Vendor buy prices (copper) from Blizzard Classic Era ItemSparse, wago.tools build %s." % BUILD)
print("-- Game data (c) Blizzard Entertainment, used as facts. Reputation discounts are ignored.")
print("local _, ns = ...")
print("ns.VENDOR_SEED = {")
for n in NAMES:
    i, p = found[n]
    print("  [%d] = %d, -- %s" % (i, p, n))
print("}")
