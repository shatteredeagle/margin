#!/usr/bin/env python3
"""Generate Margin/VendorData.lua: unit buy prices (copper) of trade goods vendors sell without limit.

Two sources, Forever's own first:
 1. EG Link output for WoW: Forever (Efficient Games, CC BY 4.0), vendors.json: every unlimited
    plain-gold item entry of trade goods / reagents (item class 7 / 5), price / stack, highest seen
    (the base price: reputation discounts only lower it).
 2. Blizzard Classic Era ItemSparse, BuyPrice / VendorStackCount, for the names in EXTRA that no
    opened vendor has shown yet.

Usage: gen_vendor.py vendors.json Item.csv ItemSparse.csv > Margin/VendorData.lua
"""
import csv, json, sys

vendors_json, item_csv, sparse_csv = sys.argv[1:4]
EXTRA = [
    "Coarse Thread", "Fine Thread", "Silken Thread", "Heavy Silken Thread", "Rune Thread", "Salt", "Bleach",
    "Empty Vial", "Leaded Vial", "Crystal Vial", "Imbued Vial",
    "Red Dye", "Green Dye", "Blue Dye", "Yellow Dye", "Purple Dye", "Gray Dye", "Black Dye",
    "Mild Spices", "Hot Spices", "Soothing Spices", "Weak Flux", "Coal", "Flash Powder", "Simple Wood",
    "Flint and Tinder", "Wooden Stock", "Heavy Stock",
]

klass = {}
for r in csv.DictReader(open(item_csv, newline="", encoding="utf-8")):
    klass[int(r["ID"])] = int(r["ClassID"])

data = json.load(open(vendors_json))
meta = data["meta"]
prices = {}  # item -> (unit price, name, source)
for v in data["vendors"].values():
    for key, e in (v.get("entries") or {}).items():
        item = e.get("itemId")
        if not key.startswith("item:") or klass.get(item) not in (7, 5):
            continue
        if e.get("limited") or e.get("costItems") or not e.get("costs"):
            continue
        unit = max(e["costs"].values()) / max(1, e.get("stack") or 1)
        if item not in prices or unit > prices[item][0]:  # base price: discounts only lower it
            prices[item] = (unit, e["name"], "forever")

found = {}
for r in csv.DictReader(open(sparse_csv, newline="", encoding="utf-8")):
    n = r["Display_lang"]
    if n in EXTRA and int(r["BuyPrice"] or 0) > 0:
        if n in found:
            sys.exit("ambiguous name: " + n)
        found[n] = (int(r["ID"]), int(r["BuyPrice"]) / max(1, int(r["VendorStackCount"] or 1)))
for n in EXTRA:
    if n not in found:
        sys.exit("not found: " + n)
    i, unit = found[n]
    if i not in prices:
        prices[i] = (unit, n, "era")

print("-- Generated by tools/gen_vendor.py. Do not edit.")
print("-- Unit buy prices (copper) of items vendors sell without limit; reputation discounts ignored.")
print("-- Data from Efficient Games (https://efficient.games), EG Link output for WoW: Forever, CC BY 4.0,")
print("-- client build %s, plus Blizzard Classic Era ItemSparse (wago.tools) for items no opened vendor showed yet." % meta["clientBuild"])
print("local _, ns = ...")
print("ns.VENDOR_SEED = {")
for item in sorted(prices):
    unit, name, src = prices[item]
    print("  [%d] = %s, -- %s (%s)" % (item, ("%d" % round(unit)) if unit == int(unit) else ("%.2f" % unit), name.replace("\n", " "), src))
print("}")
