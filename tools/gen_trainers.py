#!/usr/bin/env python3
"""Generate Margin/TrainerData.lua: which recipes profession trainers teach, at what skill, for how much.

Source: EG Link output for World of Warcraft: Forever (Efficient Games, CC BY 4.0),
https://github.com/JIVESCORP/eg-link-output-wowf  ->  data/wowf/<build>/trainers.json

Usage: gen_trainers.py trainers.json > Margin/TrainerData.lua
"""
import json, sys

d = json.load(open(sys.argv[1]))
meta = d["meta"]
best = {}  # (profession, spellId) -> [lowest rank, highest fee seen]
for trainer in d["trainers"].values():
    if trainer.get("trainerType") != 2:
        continue
    for s in trainer["services"].values():
        prof, rank = s.get("skill"), s.get("skillRank")
        # skip rank-up lessons (Journeyman etc.), which have step set
        if not isinstance(prof, str) or not isinstance(rank, int) or s.get("step"):
            continue
        fee = max(s.get("costs", {"0": 0}).values())
        key = (prof, int(s["spellId"]))
        cur = best.get(key)
        if cur is None:
            best[key] = [rank, fee, s["name"]]
        else:
            cur[0] = min(cur[0], rank)
            cur[1] = max(cur[1], fee)

print("-- Generated by tools/gen_trainers.py. Do not edit.")
print("-- Data from Efficient Games (https://efficient.games), EG Link output for WoW: Forever,")
print("-- licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).")
print("-- Client build %s, collected %s to %s. Reduced to recipe, required skill and fee;" % (
    meta["clientBuild"], meta["collectedOn"]["first"], meta["collectedOn"]["last"]))
print("-- the highest fee seen is kept (reputation discounts ignored).")
print("-- ns.TRAINER[profession][recipeSpellID] = { required skill, fee in copper }")
print("local _, ns = ...")
print("ns.TRAINER = {")
profs = sorted({p for p, _ in best})
for p in profs:
    print('  [%s] = {' % json.dumps(p))
    for (pp, sid), (rank, fee, name) in sorted(best.items(), key=lambda kv: (kv[0][0], kv[1][0], kv[0][1])):
        if pp == p:
            print("    [%d] = { %d, %d }, -- %s" % (sid, rank, fee, name))
    print("  },")
print("}")
