#!/usr/bin/env python3
"""Generate Margin/GapData.lua: how far apart a recipe's skill-up colours are.

From Blizzard's Classic Era SkillLineAbility table (wago.tools build 1.15.9.70576), used as facts:
for each trade skill recipe, TrivialSkillLineRankHigh - TrivialSkillLineRankLow, the width of the
green band in Classic. Forever's bands are about half as wide (checked against 41 recipes of a
Forever Leatherworker: grey level minus 2 x half the gap predicts the orange/yellow edge and grey
minus half the gap the yellow/green edge for every one of them), so Margin uses gap / 2.

Usage: gen_gaps.py SkillLineAbility.csv > Margin/GapData.lua
"""
import csv, sys

SKILLS = {"171", "164", "185", "333", "202", "129", "165", "197", "186"}
gaps = {}
for r in csv.DictReader(open(sys.argv[1], newline="", encoding="utf-8")):
    if r["SkillLine"] in SKILLS:
        hi, lo = int(r["TrivialSkillLineRankHigh"]), int(r["TrivialSkillLineRankLow"])
        if hi > lo:
            gaps[int(r["Spell"])] = hi - lo

print("-- Generated by tools/gen_gaps.py. Do not edit.")
print("-- Classic Era recipe colour gaps (wago.tools build 1.15.9.70576), used as facts.")
print("-- ns.GAP[recipeSpellID] = grey level minus green level in Classic; Forever's bands are about half that.")
print("local _, ns = ...")
print("ns.GAP = {")
line = []
for spell in sorted(gaps):
    line.append("[%d]=%d" % (spell, gaps[spell]))
    if len(line) == 8:
        print("  " + ", ".join(line) + ",")
        line = []
if line:
    print("  " + ", ".join(line) + ",")
print("}")
