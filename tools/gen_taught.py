#!/usr/bin/env python3
"""Generate Margin/TaughtData.lua: which recipe item (pattern, plan, recipe...) teaches which craft.

From Blizzard's Classic Era tables (wago.tools build 1.15.9.70576), used as facts:
Item (recipe items are ClassID 9), ItemSparse (name, required skill rank), ItemEffect (the item's use
spell) and SpellEffect (effect 36, learn spell -> the craft). Forever's own required skill is read from
the item's tooltip in game; the rank here is only a fallback.

Usage: gen_taught.py Item.csv ItemSparse.csv ItemEffect.csv SpellEffect.csv > Margin/TaughtData.lua
"""
import csv, sys, collections

item_csv, sparse_csv, effect_csv, spelleffect_csv = sys.argv[1:5]
# Recipe item subclass -> trade skill line
SKILL = {1: 165, 2: 197, 3: 202, 4: 164, 5: 185, 6: 171, 7: 129, 8: 333}

sub = {}
for r in csv.DictReader(open(item_csv, newline="", encoding="utf-8")):
    if r["ClassID"] == "9" and int(r["SubclassID"]) in SKILL:
        sub[int(r["ID"])] = SKILL[int(r["SubclassID"])]
rank = {}
for r in csv.DictReader(open(sparse_csv, newline="", encoding="utf-8")):
    i = int(r["ID"])
    if i in sub:
        rank[i] = int(r["RequiredSkillRank"] or 0)
use = collections.defaultdict(list)
for r in csv.DictReader(open(effect_csv, newline="", encoding="utf-8")):
    i = int(r["ParentItemID"])
    if i in sub and r["TriggerType"] == "0":
        use[i].append(int(r["SpellID"]))
learn = collections.defaultdict(list)
for r in csv.DictReader(open(spelleffect_csv, newline="", encoding="utf-8")):
    if r["Effect"] == "36":
        learn[int(r["SpellID"])].append(int(r["EffectTriggerSpell"]))

taught = collections.defaultdict(set)
for i, spells in use.items():
    for sp in spells:
        for craft in learn.get(sp, []):
            if craft == 0:
                continue  # learn effects with no craft behind them
            taught[craft].add((i, sub[i], rank.get(i, 0)))

print("-- Generated by tools/gen_taught.py. Do not edit.")
print("-- Recipe items from Blizzard Classic Era tables (wago.tools build 1.15.9.70576), used as facts.")
print("-- ns.TAUGHT[craftSpellID] = { { recipeItemID, skillLine, fallback required rank }, ... }")
print("local _, ns = ...")
print("ns.TAUGHT = {")
for craft in sorted(taught):
    items = ", ".join("{ %d, %d, %d }" % t for t in sorted(taught[craft]))
    print("  [%d] = { %s }," % (craft, items))
print("}")
